"""Convert Zendesk article HTML into clean, chunk-friendly Markdown.

Cleaning rules (applied before Markdown conversion):
- drop scripts/styles and the closing boilerplate ("That's all!" + contact blurb)
- turn single-column "NOTE / TIP / IMPORTANT" tables into blockquotes
- rewrite in-page anchors (#WhatYoullNeed) to the slug of the target heading
- make root-relative and protocol-relative URLs absolute
- replace embedded iframes (YouTube, Canva) with plain links
- drop images without alt text and inline base64 images
- strip presentational markup (span, style, class, data-* attributes)
"""
from __future__ import annotations

import re
from urllib.parse import urljoin

from bs4 import BeautifulSoup, NavigableString, Tag
from markdownify import MarkdownConverter

from .scraper import Article

HEADINGS = ["h1", "h2", "h3", "h4", "h5", "h6"]
WRAPPERS = {"div", "article", "section"}
KEEP_ATTRS: dict[str, set[str]] = {
    "a": {"href"},
    "img": {"src", "alt"},
    "code": {"class"},
    "td": {"colspan", "rowspan"},
    "th": {"colspan", "rowspan"},
}
CALLOUT_LABEL_MAX_LEN = 25

# Closing boilerplate repeated across articles; only stripped from the end of a body.
_BOILERPLATE_RES = [
    re.compile(r"^that['’]s (all|it)\b.{0,40}$", re.IGNORECASE),
    re.compile(r"^congratulations?\b", re.IGNORECASE),
    re.compile(r"leader in digital signage", re.IGNORECASE),
    re.compile(r"\bquestions\b.*\b(feedback|support@|reach out|let us know)", re.IGNORECASE),
    re.compile(r"\bfeedback\b.*\b(support@|let us know)", re.IGNORECASE),
]
_BOILERPLATE_MAX_LEN = 400
# Extra rules for the Markdown-level tail pass (catches blurbs mixed into other blocks).
_TAIL_RES = _BOILERPLATE_RES + [
    re.compile(r"^that['’]s (all|it)\b.{0,100}$", re.IGNORECASE),
    re.compile(r"\b(reach out|contact us)\b.*support@", re.IGNORECASE),
]
_MD_LINK_RE = re.compile(r"\[([^\]]*)\]\([^)]*\)")
_INTRO_RE = re.compile(r"^in this article\b", re.IGNORECASE)
_ZERO_WIDTH_RE = re.compile("[​‌‍﻿]")


def github_slug(text: str) -> str:
    """Heading anchor as generated by GitHub-flavoured Markdown renderers."""
    slug = re.sub(r"[^\w\- ]", "", text.strip().lower())
    return slug.replace(" ", "-")


def _text(el: Tag) -> str:
    return " ".join(el.get_text(" ", strip=True).split())


def _last_tag(container: Tag) -> Tag | None:
    for child in reversed(container.contents):
        if isinstance(child, Tag):
            return child
        if isinstance(child, NavigableString) and child.strip():
            return None  # trailing loose text: stop, never strip real content
    return None


def _is_boilerplate(el: Tag) -> bool:
    text = _text(el)
    if el.name == "hr" or (not text and el.find("img") is None):
        return True
    if len(text) > _BOILERPLATE_MAX_LEN:
        return False
    return any(rx.search(text) for rx in _BOILERPLATE_RES)


def _strip_footer(container: Tag) -> None:
    """Remove boilerplate blocks from the end of the article (recursing into wrappers)."""
    while (last := _last_tag(container)) is not None:
        if last.name in WRAPPERS:
            _strip_footer(last)
            if _text(last) or last.find("img") is not None:
                return
            last.decompose()
        elif _is_boilerplate(last):
            last.decompose()
        else:
            return


def _demote_intro(soup: BeautifulSoup) -> None:
    """The leading 'In this article, ...' line is styled as a heading; make it a paragraph."""
    first = soup.find(HEADINGS)
    if first is not None and _INTRO_RE.match(_text(first)):
        first.name = "p"
    for h1 in soup.find_all("h1"):  # the document title is the only H1
        h1.name = "h2"


def _convert_callouts(soup: BeautifulSoup) -> None:
    """Single-column tables are callout boxes, not data: render them as blockquotes."""
    for table in soup.find_all("table"):
        if table.find_parent("table") is not None:
            continue
        rows = table.find_all("tr")
        if not rows or any(len(r.find_all(["td", "th"], recursive=False)) > 1 for r in rows):
            continue
        quote = soup.new_tag("blockquote")
        for i, row in enumerate(rows):
            cell = row.find(["td", "th"])
            if cell is None:
                continue
            label = _text(cell)
            if i == 0 and len(rows) > 1 and 0 < len(label) <= CALLOUT_LABEL_MAX_LEN:
                para = soup.new_tag("p")
                strong = soup.new_tag("strong")
                strong.string = f"{label.rstrip(':')}:"
                para.append(strong)
                quote.append(para)
                continue
            if not cell.find(["p", "ul", "ol", "pre", "div"]):
                para = soup.new_tag("p")
                for child in list(cell.contents):
                    para.append(child.extract())
                quote.append(para)
            else:
                for child in list(cell.contents):
                    quote.append(child.extract())
        outer = table.parent if table.parent is not None and table.parent.name == "figure" else table
        outer.replace_with(quote)


def _rewrite_anchors(soup: BeautifulSoup) -> None:
    """Point '#Name' links at the Markdown slug of the heading that follows <a name="Name">."""
    slug_by_heading: dict[int, str] = {}
    seen: dict[str, int] = {}
    anchor_map: dict[str, str] = {}
    for h in soup.find_all(HEADINGS):
        base = github_slug(_text(h))
        n = seen.get(base, 0)
        seen[base] = n + 1
        slug = base if n == 0 else f"{base}-{n}"
        slug_by_heading[id(h)] = slug
        if h.get("id"):
            anchor_map[str(h["id"])] = slug

    for target in soup.find_all("a", attrs={"name": True}):
        heading = target.find_next(HEADINGS)
        if heading is not None:
            anchor_map[str(target["name"])] = slug_by_heading[id(heading)]
        parent = target.parent
        target.decompose()
        if isinstance(parent, Tag) and parent.name == "p" and not _text(parent) and parent.find("img") is None:
            parent.decompose()

    for link in soup.find_all("a", href=True):
        href = str(link["href"])
        if href.startswith("#") and href[1:] in anchor_map:
            link["href"] = f"#{anchor_map[href[1:]]}"


def _absolutize(url: str, base_url: str) -> str:
    if url.startswith("//"):
        return f"https:{url}"
    if url.startswith("/"):
        return urljoin(f"{base_url}/", url)
    return url


def _replace_iframes(soup: BeautifulSoup, base_url: str) -> None:
    for frame in soup.find_all("iframe"):
        src = _absolutize(str(frame.get("src") or ""), base_url)
        if not src:
            frame.decompose()
            continue
        kind = "video" if "youtube" in src else "Canva design" if "canva.com" in src else "content"
        para = soup.new_tag("p")
        link = soup.new_tag("a", href=src)
        link.string = f"Embedded {kind}"
        para.append(link)
        frame.replace_with(para)


def _drop_noise_images(soup: BeautifulSoup) -> None:
    """Images carry no text for retrieval; keep only those with alt text, never inline base64."""
    for img in soup.find_all("img"):
        src = str(img.get("src") or "")
        alt = str(img.get("alt") or "").strip()
        if src.startswith("data:") or not alt:
            img.decompose()
    for tag in soup.find_all(["strong", "b", "em", "i", "a", "p"]):
        if tag.parent is not None and not tag.get_text(strip=True) and tag.find("img") is None:
            tag.decompose()


def _strip_presentation(soup: BeautifulSoup, base_url: str) -> None:
    for tag in soup.find_all(["span", "font", "u", "colgroup", "col"]):
        if tag.parent is None:  # already removed together with its parent
            continue
        if tag.name in ("colgroup", "col"):
            tag.decompose()
        else:
            tag.unwrap()
    for tag in soup.find_all(True):
        allowed = KEEP_ATTRS.get(tag.name, set())
        tag.attrs = {k: v for k, v in tag.attrs.items() if k in allowed}
        for attr in ("href", "src"):
            if attr in tag.attrs:
                tag[attr] = _absolutize(str(tag[attr]), base_url)


def clean_html(html: str, base_url: str) -> BeautifulSoup:
    soup = BeautifulSoup(_ZERO_WIDTH_RE.sub("", html), "html.parser")
    for tag in soup.find_all(["script", "style", "noscript"]):
        tag.decompose()
    _strip_footer(soup)
    _demote_intro(soup)
    _convert_callouts(soup)
    _rewrite_anchors(soup)
    _replace_iframes(soup, base_url)
    _drop_noise_images(soup)
    _strip_presentation(soup, base_url)
    return soup


def _code_language(el: Tag) -> str:
    code = el.find("code")
    classes = code.get("class", []) if isinstance(code, Tag) else []
    for cls in classes:
        if cls.startswith("language-") and cls != "language-auto":
            return cls.removeprefix("language-")
    return ""


_CONVERTER = MarkdownConverter(
    heading_style="ATX",
    bullets="-",
    escape_underscores=False,
    escape_misc=False,
    table_infer_header=True,
    code_language_callback=_code_language,
)


def _strip_trailing_boilerplate(md: str) -> str:
    """Drop closing boilerplate lines left at the very end of the Markdown."""
    lines = md.rstrip().split("\n")
    while lines:
        if lines[-1].lstrip().startswith("```"):
            break  # never touch code fences
        text = re.sub(r"[#>*_`]", "", _MD_LINK_RE.sub(r"\1", lines[-1])).strip()
        removable = not text or set(text) <= {"-"} or (
            len(text) <= _BOILERPLATE_MAX_LEN and any(rx.search(text) for rx in _TAIL_RES)
        )
        if not removable:
            break
        lines.pop()
    return "\n".join(lines)


def html_to_markdown(html: str, base_url: str) -> str:
    md = _CONVERTER.convert_soup(clean_html(html, base_url))
    md = md.replace("\xa0", " ")
    md = md.replace("****", "")  # adjacent <strong> runs, e.g. "**P****review**"
    md = re.sub(r"[ \t]+\n", "\n", md)
    md = re.sub(r"\n{3,}", "\n\n", md)
    return _strip_trailing_boilerplate(md).strip()


def render_document(article: Article, body_markdown: str) -> str:
    """Full document: title + source line (used by the assistant for citations) + body."""
    header = [
        f"# {article.title}",
        "",
        f"Article URL: {article.html_url}",
        f"Last updated: {article.updated_at}",
        "",
    ]
    return "\n".join(header) + "\n" + body_markdown + "\n"


def article_to_markdown(article: Article, base_url: str) -> str:
    return render_document(article, html_to_markdown(article.body, base_url))
